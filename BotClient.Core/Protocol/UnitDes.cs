    /// <summary>
    /// = Delphi <c>EncryptDes(Indata; var Outdata; Length(data); Key)</c>(UnitDes.pas:995),
    /// 也即 <c>EncryptStrDes</c>(UnitDes.pas:1031)的 <c>SetLength(Result, Length(Source))</c> + 整块处理。
    /// 产出的字节串可被 gate 侧 Delphi 的 <c>DecryptDes</c>(原地处理 <c>Length(sRecv)</c> 字节)逐字节解回,
    /// 因为这里的分块边界/链推进/尾部处理与 Delphi 完全一致(Delphi 允许 Indata 与 Outdata 是同一缓冲区,
    /// 本实现输出到新数组; 两条路径下每个字节的取值都一样)。
    /// </summary>
    /// <param name="data">明文字节(对应 Delphi 的 Indata 指针, Size = Length(data))。</param>
    /// <param name="key">AnsiString 密钥, 例如 <c>IntToStr(pw)</c>; 数字串下 ASCII 字节 == GBK 字节。</param>
    /// <returns>新分配的密文数组, 长度与 <paramref name="data"/> 相同(无填充)。</returns>
    public static byte[] EncryptDes(byte[] data, string key)
    {
        ArgumentNullException.ThrowIfNull(data);
        ArgumentNullException.ThrowIfNull(key);

        var outData = new byte[data.Length];
        // Delphi EncryptDes 的局部变量: KeyData: array[0..31] of DWord; Chain: array[0..BS-1] of Byte;
        Span<uint> keyData = stackalloc uint[32];
        Span<byte> chain = stackalloc byte[Bs];

        GetKeyData(key, chain, keyData);
        EncryptCBC(data, outData, data.Length, chain, keyData);
        return outData;
    }

    /// <summary>
    /// = Delphi <c>DecryptDes(Indata; var Outdata; Length(cipher); Key)</c>(UnitDes.pas:1004)。
    /// 注意它并不是"每块 DecryptBlock + 逆链":不足 20 字节的尾巴沿用 **EncryptBlock(Chain,Chain)**
    /// (UnitDes.pas:939),这正是 <see cref="EncryptCBC"/> 尾部写法(UnitDes.pas:913)的逆操作,原样保留 ——
    /// 改成 DecryptBlock 会让 &lt;20 字节的包体解不出来。
    /// </summary>
    public static byte[] DecryptDes(byte[] cipher, string key)
    {
        ArgumentNullException.ThrowIfNull(cipher);
        ArgumentNullException.ThrowIfNull(key);

        var outData = new byte[cipher.Length];
        Span<uint> keyData = stackalloc uint[32];
        Span<byte> chain = stackalloc byte[Bs];

        GetKeyData(key, chain, keyData);
        DecryptCBC(cipher, outData, cipher.Length, chain, keyData);
        return outData;
    }

