/// <summary>
/// UnitDes.pas (D:\gxx\Delphi7\Source\Common\UnitDes.pas, Delphi 7) 的逐字移植 —— Mir2 协议
/// LoginGate 上行包体加解密用的就是这个非标准链式 DES, 任何"改用标准 DES-CBC"的"优化"都会直接导致协议不兼容。
///
/// 非标准在哪里: 底层 8 字节分组确实是表驱动(Gladman/OpenSSL des_skb + des_SPtrans 风格)的**标准 DES**
/// (与 .NET <c>DES</c> 的 300 组随机 key/block 逐组比对全等, 且 FIPS-46 官方向量
/// <c>0123456789ABCDEF</c>/<c>"Now is t"</c> → <c>3FA40E8A984D4815</c> 亦相同), 但外层链式分组
/// <c>BS = 20</c> 字节, 而且
/// <see cref="EncryptBlock"/> 每个 20 字节链块里只处理**前 8 个字节**(Delphi: <c>PDword(@InData)^</c> /
/// <c>PDword(IntPtr(@InData) + 4)^</c>), 第 9..20 字节只与链值做 <c>XorBlock</c>, 完全不经过 DES。
/// 所以密文长度 == 明文长度、无填充、无 MAC, 与任何标准 DES 模式都不兼容。
///
/// 密钥派生(<see cref="GetKeyData"/>, UnitDes.pas:810):
///  1) <c>Hash(Key, Digest)</c> —— UnitHash.pas:80 是手写教科书版 SHA-1(标准 IV/轮常量/大端长度/大端输出),
///     与 .NET <see cref="SHA1"/> 逐字节一致, 因此这里直接用 <see cref="SHA1"/>;
///  2) 摘要**前 8 字节**作 DES 密钥(后 12 字节被丢弃, <c>Move(Digest, KeyB, SizeOf(KeyB))</c>);
///  3) 初始链值 = 20 字节全 $8F 的 IV 做**一次** <see cref="EncryptBlock"/>(故 chain[8..19] 仍是 $8F)。
///
/// 尾部(&lt; 20 字节)处理(UnitDes.pas:911/937, 原样保留): 先把**当前 chain 整体**做一次
/// <see cref="EncryptBlock"/>(仍只有前 8 字节被变换, 9..20 保持上文的链值), 再把尾部字节原样拷出后与该
/// chain 逐字节异或; 尾部不再回写 chain, 也不补齐 —— 因此 <c>rem &gt; 8</c> 时尾部第 9..rem 个字节
/// 异或的是"未被 DES 处理的旧链值", 这正是加/解密能对称往返的关键。
///
/// 同族单元(<c>RunGate/LoginGate/M2Engine/Client-HGE</c> 各自的 <c>DesUtils.pas</c>)的 <c>BS</c> 同样是 20,
/// 但它们另有 <c>*_New/_New2</c> 路径: 把 <c>perm_op</c> 的掩码 <c>$33333333</c> 写成 <c>$33333331</c>
/// (人为改坏的置换, 于是分组核**不再是**标准 DES), 密钥也不是 SHA-1 而是 CRC+混合(用 <c>crc_table</c>,
/// 该表在那些单元里有 19 处引用; 本单元只是照抄未用)。
/// <b>本类只对应 Common/UnitDes.pas 这条 SHA-1 派生 + 标准掩码的路径, 两套不能混用。</b>
///
/// 公开语义 = Delphi <c>EncryptDes(Indata; var Outdata; Size; Key)</c> / <c>DecryptDes(...)</c>
/// (UnitDes.pas:995/1004) + <c>EncryptStrDes/DecryptStrDes</c>(1031/1037) 的 "SetLength(Result, Length(Source))"。
/// Delphi 那边 Indata/Outdata 允许是同一块缓冲区(原地处理), 本类的分块/推进方式与之逐字节等价,
/// 只是返回新数组。Key 在 Delphi 侧是 AnsiString(实际取 <c>IntToStr(pw)</c> 这类数字串), 按
/// "每字符取低 8 位"折算(数字字符下 ASCII == GBK)。
///
/// 源文件里未被本路径使用、因此**未移植**的过程: <c>GetKeyDataPak/GetKeyDataPak2/GetKeyData3</c>
/// (UnitDes.pas:831/850/875, PAK 包专用, IV 填充值改为 $60/$4F)、<c>EncryptCBC3/DecryptCBC3</c>
/// (945/969) 与 <c>EncryptBlock3/DecryptBlock3</c>(796/803, 112 位三重 DES 变体)、
/// <c>EncryStringHex/DecryStringHex</c>(1043/1081)、<c>PakEncryKey/NewEncryKey/PakEncryKey2</c> 全局
