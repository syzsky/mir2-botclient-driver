    /// UnitDes.pas:895 <c>EncryptCBC</c>。
    /// p1/p2 是输入/输出游标, Size 为字节数; 每 20 字节: 整块拷出 -&gt; 与 Chain 逐字节异或 -&gt;
    /// **只把前 8 字节过 DES** -&gt; 把这 20 字节密文写回 Chain。
    /// 尾块(&lt; 20 字节): Chain 先整体 EncryptBlock(原地, 只有前 8 字节变), 再拷出尾块并与 Chain 异或。
    internal static void EncryptCBC(ReadOnlySpan<byte> inData, Span<byte> outData, int size, Span<byte> chain, Span<uint> keyData)
    {
        int p1 = 0;
        int p2 = 0;

        // for i := 1 to (Size div BS) do
        for (int i = 1; i <= size / Bs; i++)
        {
            inData.Slice(p1, Bs).CopyTo(outData.Slice(p2, Bs));            // Move(p1^, p2^, BS)
            XorBlock(outData.Slice(p2, Bs), chain, Bs);                    // XorBlock(p2^, Chain^, BS)
            EncryptBlock(outData.Slice(p2, 8), outData.Slice(p2, 8), keyData); // EncryptBlock(p2^, p2^, KeyData) —— 8 字节
            outData.Slice(p2, Bs).CopyTo(chain);                           // Move(p2^, Chain^, BS)
            p1 += Bs;
            p2 += Bs;
        }

        int rem = size % Bs;
        if (rem != 0)
        {
            EncryptBlock(chain.Slice(0, 8), chain.Slice(0, 8), keyData);   // EncryptBlock(Chain^, Chain^, KeyData)
            inData.Slice(p1, rem).CopyTo(outData.Slice(p2, rem));          // Move(p1^, p2^, Size mod BS)
            XorBlock(outData.Slice(p2, rem), chain.Slice(0, rem), rem);    // XorBlock(p2^, Chain^, Size mod BS)
        }
    }

    /// UnitDes.pas:919 <c>DecryptCBC</c>。
    /// 整块: 拷入 -&gt; 备份密文到 Temp -&gt; DecryptBlock(前 8 字节) -&gt; 与 Chain 异或 20 字节 -&gt;
    /// Chain := 该块**密文**(Temp)。尾块用的是 EncryptBlock(Chain) 而不是 DecryptBlock —— 原样保留,
    /// 否则与 EncryptCBC 的尾块不对称, 往返就会失败。
    internal static void DecryptCBC(ReadOnlySpan<byte> inData, Span<byte> outData, int size, Span<byte> chain, Span<uint> keyData)
    {
        int p1 = 0;
        int p2 = 0;
        Span<byte> temp = stackalloc byte[Bs];

        for (int i = 1; i <= size / Bs; i++)
        {
            inData.Slice(p1, Bs).CopyTo(outData.Slice(p2, Bs));            // Move(p1^, p2^, BS)
            inData.Slice(p1, Bs).CopyTo(temp);                             // Move(p1^, Temp, BS)
            DecryptBlock(outData.Slice(p2, 8), outData.Slice(p2, 8), keyData); // DecryptBlock(p2^, p2^, KeyData)
            XorBlock(outData.Slice(p2, Bs), chain, Bs);                    // XorBlock(p2^, Chain^, BS)
            temp.CopyTo(chain);                                            // Move(Temp, Chain^, BS)
            p1 += Bs;
            p2 += Bs;
        }

        int rem = size % Bs;
        if (rem != 0)
        {
            EncryptBlock(chain.Slice(0, 8), chain.Slice(0, 8), keyData);   // EncryptBlock(Chain^, Chain^, KeyData)
            inData.Slice(p1, rem).CopyTo(outData.Slice(p2, rem));
            XorBlock(outData.Slice(p2, rem), chain.Slice(0, rem), rem);
        }
    }

    /// UnitHash.pas:37 <c>XorBlock</c>:逐字节 <c>InData1[i] := InData1[i] xor InData2[i]</c>(i = 1..Size)。
    private static void XorBlock(Span<byte> data1, ReadOnlySpan<byte> data2, int size)
    {
        for (int i = 0; i < size; i++)
            data1[i] = (byte)(data1[i] ^ data2[i]);
    }

    /// <summary>
    /// Delphi 侧 Key 是 AnsiString(1 字符 = 1 字节)。密钥实际来源是 <c>IntToStr(pw)</c> 这类数字串,
    /// 因此这里按 AnsiChar 的隐式转换规则取字符低 8 位(数字字符下 ASCII 码 == GBK 码, 与 Delphi 内部
    /// 的 GBK 折算结果相同); 空串时对应 <c>Update(Key[1], 0)</c>(Size = 0, 不解引用指针)
    /// → SHA-1 的空消息摘要, 行为一致。
    /// 限制: 若密钥可能含非 ASCII 字符, Delphi 那边喂给 SHA-1 的是 AnsiString 里已编码好的 GBK 字节,
    /// 与"取低 8 位"不等价 —— 实际协议里密钥恒为 <c>IntToStr(...)</c> 的十进制数字串, 故不受影响。
    /// </summary>
    private static byte[] ToAnsiBytes(string key)
    {
        var bytes = new byte[key.Length];
        for (int i = 0; i < bytes.Length; i++)
            bytes[i] = unchecked((byte)key[i]);
        return bytes;
    }
