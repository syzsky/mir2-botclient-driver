    /// <summary>
    /// UnitDes.pas:810 <c>GetKeyData</c>。
    /// </summary>
    internal static void GetKeyData(string key, Span<byte> chain, Span<uint> keyData)
    {
        // Hash(Key, Digest);                                   -- UnitHash.pas:80, SHA-1(Ansi 字节)
        byte[] digest = SHA1.HashData(ToAnsiBytes(key));

        // FillChar(KeyB, Sizeof(KeyB), 0); Move(Digest, KeyB, SizeOf(KeyB));
        // KeyB 是 8 字节, 只填 0 后拷进摘要前 8 字节(摘要长 20, 后 12 字节被丢弃)。
        Span<byte> keyB = stackalloc byte[8];
        digest.AsSpan(0, 8).CopyTo(keyB);
        DoInit(keyB, keyData);

        // FillChar(IV, BS, $8F);                              -- 不是 $6F(源码里那行被注释掉)
        // EncryptBlock(IV, IV, KeyData);                      -- 原地: 只有 IV[0..7] 被 DES 变换
        // Move(IV, Chain^, BS);
        Span<byte> iv = stackalloc byte[Bs];
        iv.Fill(0x8F);
        EncryptBlock(iv, iv, keyData);
        iv.CopyTo(chain);
    }

    /// UnitDes.pas:564 <c>DoInit</c> —— Gladman des_set_key 的 Delphi 版。
    internal static void DoInit(ReadOnlySpan<byte> keyB, Span<uint> keyData)
    {
        // c := KeyB^[0] or (KeyB^[1] shl 8) or (KeyB^[2] shl 16) or (KeyB^[3] shl 24);
        // d := KeyB^[4] or (KeyB^[5] shl 8) or (KeyB^[6] shl 16) or (KeyB^[7] shl 24);
        // Delphi 的 shl 作用在 Byte 操作数上时按 32 位寄存器计算(不在 8 位上截断/回绕),
        // 因此等价于两次小端 32 位读取。注意: KeyB 长度只有 8, 这里读满 8 字节。
        // 这一折算(以及整套 IP/FP/轮表)已被"300 组随机 key/block 的 EncryptBlock 与 .NET 标准 DES-ECB
        // 逐字节全等 + FIPS-46 官方向量"证实, 不是猜的。
        uint c = BinaryPrimitives.ReadUInt32LittleEndian(keyB);
        uint d = BinaryPrimitives.ReadUInt32LittleEndian(keyB.Slice(4));

        PermOp(ref d, ref c, 4, 0x0F0F0F0F);
        // hperm_op(c, t, dword(-2), $CCCC0000)  -- 实参是 dword(-2) = $FFFFFFFE
        HpermOp(ref c, 0xFFFFFFFE, 0xCCCC0000);
        HpermOp(ref d, 0xFFFFFFFE, 0xCCCC0000);
        PermOp(ref d, ref c, 1, 0x55555555);
        PermOp(ref c, ref d, 8, 0x00FF00FF);
        PermOp(ref d, ref c, 1, 0x55555555);

        d = unchecked(((d & 0xFF) << 16) | (d & 0xFF00) | ((d & 0x00FF0000) >> 16) | ((c & 0xF0000000) >> 4));
        c &= 0x0FFFFFFF;

        for (int i = 0; i <= 15; i++)
        {
            if (Shifts2[i] != 0)
            {
                c = (c >> 2) | (c << 26);
                d = (d >> 2) | (d << 26);
            }
            else
            {
                c = (c >> 1) | (c << 27);
                d = (d >> 1) | (d << 27);
            }

            c &= 0x0FFFFFFF;
            d &= 0x0FFFFFFF;

            uint s = DesSkb[0][(int)(c & 0x3F)]
                   | DesSkb[1][(int)(((c >> 6) & 0x03) | ((c >> 7) & 0x3C))]
                   | DesSkb[2][(int)(((c >> 13) & 0x0F) | ((c >> 14) & 0x30))]
                   | DesSkb[3][(int)(((c >> 20) & 0x01) | ((c >> 21) & 0x06) | ((c >> 22) & 0x38))];
            uint t = DesSkb[4][(int)(d & 0x3F)]
                   | DesSkb[5][(int)(((d >> 7) & 0x03) | ((d >> 8) & 0x3C))]
                   | DesSkb[6][(int)((d >> 15) & 0x3F)]
                   | DesSkb[7][(int)(((d >> 21) & 0x0F) | ((d >> 22) & 0x30))];

            uint t2 = unchecked((t << 16) | (s & 0xFFFF));
            keyData[i << 1] = unchecked((t2 << 2) | (t2 >> 30));
            t2 = (s >> 16) | (t & 0xFFFF0000);
            keyData[(i << 1) + 1] = unchecked((t2 << 6) | (t2 >> 26));
        }
    }

    /// UnitDes.pas:557 <c>perm_op</c>(Delphi 的 t 是出参, 这里内联成局部变量)。
    /// n 在 Delphi 里是 dword, x86 SHL/SHR 的计数按 mod 32 生效; C# 对 uint 左操作数的移位计数
    /// 也先取低 5 位, 两边语义一致(故这里用 int 传计数只是为了满足 C# 语法)。
    private static void PermOp(ref uint a, ref uint b, int n, uint m)
    {
        uint t = ((a >> n) ^ b) & m;
        b = b ^ t;
        a = unchecked(a ^ (t << n));
    }

    /// UnitDes.pas:551 <c>hperm_op</c>。
    /// 调用处传的 n = dword(-2) = $FFFFFFFE, Delphi 里 <c>16 - n</c> 按 dword 无符号运算 = $12 = 18,
    /// 之后 shl/shr 都用这个 18(x86 还会再按 mod 32 掩一次, 18 不受影响)。
    private static void HpermOp(ref uint a, uint n, uint m)
    {
        int s = unchecked((int)(16u - n));
        uint t = ((a << s) ^ a) & m;
        a = a ^ t ^ (t >> s);
    }

