    /// UnitDes.pas:608 <c>EncryptBlock</c>。InData/OutData 各 8 字节, 允许原地(in/out 同一缓冲区)。
    internal static void EncryptBlock(ReadOnlySpan<byte> inData, Span<byte> outData, ReadOnlySpan<uint> keyData)
    {
        uint r = BinaryPrimitives.ReadUInt32LittleEndian(inData);
        uint l = BinaryPrimitives.ReadUInt32LittleEndian(inData.Slice(4));

        // 初始置换 IP
        uint t = unchecked(((l >> 4) ^ r) & 0x0F0F0F0F);
        r = r ^ t;
        l = unchecked(l ^ (t << 4));
        t = ((r >> 16) ^ l) & 0x0000FFFF;
        l = l ^ t;
        r = unchecked(r ^ (t << 16));
        t = ((l >> 2) ^ r) & 0x33333333;
        r = r ^ t;
        l = unchecked(l ^ (t << 2));
        t = ((r >> 8) ^ l) & 0x00FF00FF;
        l = l ^ t;
        r = unchecked(r ^ (t << 8));
        t = ((l >> 1) ^ r) & 0x55555555;
        r = r ^ t;
        l = unchecked(l ^ (t << 1));
        r = (r >> 29) | (r << 3);
        l = (l >> 29) | (l << 3);

        // 16 轮(源码里按 8 轮一组展开成 while i &lt; 32)
        int i = 0;
        while (i < 32)
        {
            l = l ^ Round(r ^ keyData[i], r ^ keyData[i + 1]);
            r = r ^ Round(l ^ keyData[i + 2], l ^ keyData[i + 3]);
            l = l ^ Round(r ^ keyData[i + 4], r ^ keyData[i + 5]);
            r = r ^ Round(l ^ keyData[i + 6], l ^ keyData[i + 7]);
            i += 8;
        }

        // 末置换 FP
        r = (r >> 3) | (r << 29);
        l = (l >> 3) | (l << 29);
        t = ((r >> 1) ^ l) & 0x55555555;
        l = l ^ t;
        r = unchecked(r ^ (t << 1));
        t = ((l >> 8) ^ r) & 0x00FF00FF;
        r = r ^ t;
        l = unchecked(l ^ (t << 8));
        t = ((r >> 2) ^ l) & 0x33333333;
        l = l ^ t;
        r = unchecked(r ^ (t << 2));
        t = ((l >> 16) ^ r) & 0x0000FFFF;
        r = r ^ t;
        l = unchecked(l ^ (t << 16));
        t = ((r >> 4) ^ l) & 0x0F0F0F0F;
        l = l ^ t;
        r = unchecked(r ^ (t << 4));

        // PDword(@OutData)^ := l;  PDword(IntPtr(@OutData) + 4)^ := r;
        BinaryPrimitives.WriteUInt32LittleEndian(outData, l);
        BinaryPrimitives.WriteUInt32LittleEndian(outData.Slice(4), r);
    }

    /// UnitDes.pas:702 <c>DecryptBlock</c> —— 与 EncryptBlock 同结构, 只是子密钥反序
    /// (i 从 30 起、每次 -8, 共 4 组 = 16 轮; 首轮用 keyData[30]/[31], 末轮用 keyData[0]/[1])。
    ///
    /// 【为什么这样真的可逆 —— 别照着"标准 Feistel"去"修"它】
    /// 加密的 16 次半轮是 l,r,l,…,l,r(首尾分别打在 l 与 r 上), 反序后按教科书写法应当从 **r** 开始,
    /// 但这里两侧都是"从 l 开始", 看上去少了一次半区交换。它能自洽是因为本实现的 FP 并不是 IP 的逆:
    /// 对照 UnitDes.pas:615-627 与 683-695, IP 的 5 个 <c>perm_op</c> 是 (l,r,4)(r,l,16)(l,r,2)(r,l,8)(l,r,1),
    /// 而 FP 逆序写成 (r,l,1)(l,r,8)(r,l,2)(l,r,16)(r,l,4) —— 每一步的参数顺序都相对"真正的逆"
    /// 颠倒了一档; <c>perm_op(a,b,n,m)</c> 本身是对被选中那几组位的**对调**(自逆), 因此颠倒参数得到的是
    /// 另一个对合, 与原逆之间正好差教科书 DES 里那次 32 位 pre-output 半区交换。
    /// 这正好补上少掉的那次交换(实测 FP(IP(x)) != x, 但整块 DecryptBlock(EncryptBlock(x)) == x),
    /// 即 IP/FP 把教科书 DES 的 pre-output swap 折进了置换里。已验证: 300 组随机 key/block 下
    /// <c>DecryptBlock(EncryptBlock(x)) == x</c> 全等, 且 EncryptBlock 与 .NET 标准 DES-ECB 逐字节相同。
    internal static void DecryptBlock(ReadOnlySpan<byte> inData, Span<byte> outData, ReadOnlySpan<uint> keyData)
    {
        uint r = BinaryPrimitives.ReadUInt32LittleEndian(inData);
        uint l = BinaryPrimitives.ReadUInt32LittleEndian(inData.Slice(4));

        uint t = unchecked(((l >> 4) ^ r) & 0x0F0F0F0F);
        r = r ^ t;
        l = unchecked(l ^ (t << 4));
        t = ((r >> 16) ^ l) & 0x0000FFFF;
        l = l ^ t;
        r = unchecked(r ^ (t << 16));
        t = ((l >> 2) ^ r) & 0x33333333;
        r = r ^ t;
        l = unchecked(l ^ (t << 2));
        t = ((r >> 8) ^ l) & 0x00FF00FF;
        l = l ^ t;
        r = unchecked(r ^ (t << 8));
        t = ((l >> 1) ^ r) & 0x55555555;
        r = r ^ t;
        l = unchecked(l ^ (t << 1));
        r = (r >> 29) | (r << 3);
        l = (l >> 29) | (l << 3);

        int i = 30;
        while (i > 0)
        {
            l = l ^ Round(r ^ keyData[i], r ^ keyData[i + 1]);
            r = r ^ Round(l ^ keyData[i - 2], l ^ keyData[i - 1]);
            l = l ^ Round(r ^ keyData[i - 4], r ^ keyData[i - 3]);
            r = r ^ Round(l ^ keyData[i - 6], l ^ keyData[i - 5]);
            i -= 8;
        }

        r = (r >> 3) | (r << 29);
        l = (l >> 3) | (l << 29);
        t = ((r >> 1) ^ l) & 0x55555555;
        l = l ^ t;
        r = unchecked(r ^ (t << 1));
        t = ((l >> 8) ^ r) & 0x00FF00FF;
        r = r ^ t;
        l = unchecked(l ^ (t << 8));
        t = ((r >> 2) ^ l) & 0x33333333;
        l = l ^ t;
        r = unchecked(r ^ (t << 2));
        t = ((l >> 16) ^ r) & 0x0000FFFF;
        r = r ^ t;
        l = unchecked(l ^ (t << 16));
        t = ((r >> 4) ^ l) & 0x0F0F0F0F;
        l = l ^ t;
        r = unchecked(r ^ (t << 4));

        BinaryPrimitives.WriteUInt32LittleEndian(outData, l);
        BinaryPrimitives.WriteUInt32LittleEndian(outData.Slice(4), r);
    }

    /// EncryptBlock/DecryptBlock 里展开 8 次的查表式子, 合并成一个函数:
    /// <c>u</c> 直接查表, <c>t</c> 先做 <c>(t shr 4) or (t shl 28)</c> 循环右移 4 位再查表
    /// (Gladman 把奇数轮子密钥预旋转了 4 位, 见 DoInit 的 <c>t2 shl 6 / t2 shr 26</c>)。
    private static uint Round(uint u, uint t)
    {
        t = (t >> 4) | (t << 28);
        return DesSptrans[0][(int)((u >> 2) & 0x3F)]
             ^ DesSptrans[2][(int)((u >> 10) & 0x3F)]
             ^ DesSptrans[4][(int)((u >> 18) & 0x3F)]
             ^ DesSptrans[6][(int)((u >> 26) & 0x3F)]
             ^ DesSptrans[1][(int)((t >> 2) & 0x3F)]
             ^ DesSptrans[3][(int)((t >> 10) & 0x3F)]
             ^ DesSptrans[5][(int)((t >> 18) & 0x3F)]
             ^ DesSptrans[7][(int)((t >> 26) & 0x3F)];
    }

